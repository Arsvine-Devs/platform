function createTraditionalMessages() {
  const result: Messages = {};
  for (const [key, value] of Object.entries({ ...messages['zh-CN'], ...additionalMessages })) {
    result[key] = traditionalReplacements.reduce(
      (text, [from, to]) => text.replaceAll(from, to),
      value,
    );
  }
  return result;
}

