#!/usr/bin/env node
/**
 * Sync publishable site packages into sibling consumer repos.
 * Platform remains the source of truth until GitHub Packages publish is wired.
 *
 * Usage (from platform root):
 *   node scripts/sync-site-packages.mjs
 *   node scripts/sync-site-packages.mjs --check
 */
import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const platformRoot = resolve(__dirname, '..');
const checkOnly = process.argv.includes('--check');
const packageNames = ['site-config', 'service-health'];
const consumerPackageRoots = [
  resolve(platformRoot, '../realm/packages'),
  resolve(platformRoot, '../ripple-website/packages'),
];

function collectFiles(dir, base = dir, out = []) {
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) collectFiles(full, base, out);
    else out.push({ rel: full.slice(base.length + 1).replaceAll('\\', '/'), full });
  }
  return out;
}

function fingerprint(dir) {
  const hash = createHash('sha256');
  for (const { rel, full } of collectFiles(dir)) {
    if (rel === 'package.json') {
      // Ignore vendor marker when comparing.
      const pkg = JSON.parse(readFileSync(full, 'utf8'));
      delete pkg._arsvineSource;
      hash.update(rel);
      hash.update('\0');
      hash.update(JSON.stringify(pkg));
      hash.update('\0');
      continue;
    }
    hash.update(rel);
    hash.update('\0');
    hash.update(readFileSync(full));
    hash.update('\0');
  }
  return hash.digest('hex');
}

let failed = false;
for (const name of packageNames) {
  const source = join(platformRoot, 'packages', name);
  if (!existsSync(source)) {
    console.error(`[sync-site-packages] missing source ${source}`);
    process.exit(1);
  }
  const sourceFp = fingerprint(source);
  for (const consumerRoot of consumerPackageRoots) {
    const target = join(consumerRoot, name);
    if (checkOnly) {
      if (!existsSync(target) || fingerprint(target) !== sourceFp) {
        console.error(`[sync-site-packages] drift: ${target} != platform/packages/${name}`);
        failed = true;
      } else {
        console.log(`[sync-site-packages] ok ${target}`);
      }
      continue;
    }
    mkdirSync(consumerRoot, { recursive: true });
    rmSync(target, { recursive: true, force: true });
    cpSync(source, target, { recursive: true });
    const pkgPath = join(target, 'package.json');
    const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
    pkg._arsvineSource = `platform/packages/${name}@${pkg.version}`;
    writeFileSync(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`);
    console.log(`[sync-site-packages] synced ${target}`);
  }
}

if (failed) process.exit(1);
